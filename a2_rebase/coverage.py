"""A2 re-base, step 1: measure the deck + A2 queue against the official
Lithuanian A1+A2 descriptor lexicon (VU list merging Pusiaukelė (A2) and
Lūžis (A1); source PDF in sources/).

Writes:
  sources/vu_a1a2_lexicon.csv     the list, one entry per row
  a2_rebase/official_missing.csv  official entries in neither deck nor queue
  a2_rebase/queue_offlist.csv     queue rows whose target is not on the list
  a2_rebase/coverage_report.md    the numbers
Matching is case- and accent-insensitive on whole entries.
Run: python3 a2_rebase/coverage.py
"""
import csv, re, subprocess, unicodedata
from collections import Counter
csv.field_size_limit(10**7)
PDF = "sources/A2_2_lygis_VU_A1A2_lexicon.pdf"

def norm(s):
    s = unicodedata.normalize("NFD", (s or "").strip().lower())
    s = "".join(c for c in s if unicodedata.category(c) != "Mn" or c in "̨̌̇̄")
    # keep Lithuanian letters (č š ž ą ę ė į ų ū), drop only stress marks
    return re.sub(r"\s+", " ", unicodedata.normalize("NFC", s))

text = subprocess.run(["pdftotext", "-layout", PDF, "-"], capture_output=True, text=True).stdout
TITLE = "LIETUVIŲ KALBOS A2 LYGIO ŽODŽIŲ SĄRAŠAS"
body = text.split(TITLE, 2)[2]            # skip the cover page and its intro
body = body.split("Parengė:")[0]          # drop the closing credits
lex, joined, section = [], [], None
for line in body.splitlines():
    w = line.strip().strip("\f")
    if not w or w == TITLE or re.fullmatch(r"\d+", w):     # page headers, page numbers
        continue
    if re.fullmatch(r"[A-ZĄČĘĖĮŠŲŪŽ]", w):                  # section letter
        section = w.lower(); continue
    # A line that doesn't start with the section's letter is the wrapped tail
    # of a multi-word entry ("asmens tapatybės / kortelė").
    if lex and section and w[0].lower() != section:
        lex[-1] += " " + w; joined.append(lex[-1]); continue
    lex.append(w)
lex = list(dict.fromkeys(lex))
with open("sources/vu_a1a2_lexicon.csv", "w", newline="", encoding="utf-8") as f:
    wr = csv.writer(f); wr.writerow(["entry"]); wr.writerows([[w] for w in lex])

deck = list(csv.DictReader(open("cards_anki.csv", encoding="utf-8")))
queue = list(csv.DictReader(open("wordlist_a2_pending.csv", encoding="utf-8")))
deck_n = {norm(r["lithuanian"]) for r in deck}
queue_n = {norm(r["lithuanian_TARGET"]) for r in queue if r["status"] != "review-duplicate"}
lex_n = {norm(w): w for w in lex}

in_deck = [w for n, w in lex_n.items() if n in deck_n]
in_queue = [w for n, w in lex_n.items() if n in queue_n and n not in deck_n]
missing = [w for n, w in lex_n.items() if n not in deck_n and n not in queue_n]
with open("a2_rebase/official_missing.csv", "w", newline="", encoding="utf-8") as f:
    wr = csv.writer(f); wr.writerow(["entry"]); wr.writerows([[w] for w in missing])

live_q = [r for r in queue if r["status"] != "review-duplicate"]
off = [r for r in live_q if norm(r["lithuanian_TARGET"]) not in lex_n]
with open("a2_rebase/queue_offlist.csv", "w", newline="", encoding="utf-8") as f:
    cols = ["id", "phase", "level", "category", "type", "card_type", "english", "lithuanian_TARGET"]
    wr = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore"); wr.writeheader(); wr.writerows(off)
deck_off = [r for r in deck if norm(r["lithuanian"]) not in lex_n]

by_type = Counter(r["type"] for r in off)
by_phase = Counter(r["phase"] for r in off)
rep = f"""# A2 re-base — coverage against the official A1+A2 lexicon

Generated by `a2_rebase/coverage.py`. Yardstick: VU list merging *Pusiaukelė*
(A2, Ramonienė 2016) and the A1 descriptor (Stumbrienė 2016), {len(lex)} entries.
Exact whole-entry match, case- and stress-insensitive, so multi-word queue
targets and inflected forms under-match by a few points.

| | entries | share of list |
|---|---:|---:|
| on the list and already in the deck | {len(in_deck)} | {len(in_deck)/len(lex):.0%} |
| on the list, in the queue only | {len(in_queue)} | {len(in_queue)/len(lex):.0%} |
| **on the list, in neither** | **{len(missing)}** | **{len(missing)/len(lex):.0%}** |

Deck: {len(deck)} cards, {len(deck_off)} ({len(deck_off)/len(deck):.0%}) not on the list.
Queue: {len(live_q)} live rows (duplicates excluded), **{len(off)} ({len(off)/len(live_q):.0%}) off-list**.

Off-list queue rows by type: {dict(by_type.most_common())}
Off-list queue rows by phase: {dict(by_phase.most_common())}

PHRASE/sentence rows are expected to be off-list (the list holds lemmas), so
judge pruning on N/V/A rows.
"""
rep += "\nWrapped entries re-joined from the PDF layout: " + "; ".join(joined) + "\n"
open("a2_rebase/coverage_report.md", "w", encoding="utf-8").write(rep)
print(rep)
