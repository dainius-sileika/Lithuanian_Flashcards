# -*- coding: utf-8 -*-
"""Generate situations.py (repo root) from a2_build/restage_bubbles.csv
(RESTAGE_PROPOSAL §2(f)). Run after any edit to the CSV:

    python3 a2_build/src/build_situations.py

Rules:
  - a gloss that appears twice (the 9 question words, 374 galvoti) takes the LAST
    row whose `render` starts with "yes": the owner decisions of 2026-10-17 were
    appended below the superseded rows.
  - the editorial " Note: ..." tail of a staging line is commentary for the owner,
    not prompt text; it is kept in `note` and dropped from `scene`.
  - merged rows (render "no (merged)") carry `merge_with` and no scene of their own.
"""
import csv, os, pprint, re
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(ROOT, "a2_build", "restage_bubbles.csv")
OUT = os.path.join(ROOT, "situations.py")
FORMAT = {"single scene": "situation", "single scene (optional)": "situation",
          "two panels": "situation_2", "three panels": "sequence", "no image": ""}

sit = {}
for r in csv.DictReader(open(SRC, encoding="utf-8")):
    en = r["english"].strip()
    render = r["render"].strip()
    staging = r["new_staging"].strip()
    note = ""
    m = re.search(r"\s*Note:\s*(.*)$", staging)
    if m:
        note, staging = m.group(1).strip(), staging[:m.start()].rstrip(" ;,.")
    entry = {"ids": [i.strip() for i in r["ids"].split(",") if i.strip()],
             "lithuanian": r["lithuanian"].strip(), "format": FORMAT.get(r["new_format"].strip(), "situation"),
             "scene": staging, "cue": r["distinguishing_cue"].strip(),
             "confusables": [c.strip() for c in r["confusables"].split(";") if c.strip()],
             "merge_with": r["merge_with"].strip(), "render": render, "note": note,
             "source_file": r["source_file"].strip()}
    prev = sit.get(en)
    if prev is None or render.startswith("yes") or not prev["render"].startswith("yes"):
        sit[en] = entry

by_id = {}
for en, e in sit.items():
    for i in e["ids"]:
        by_id[i] = en

with open(OUT, "w", encoding="utf-8") as f:
    f.write('# -*- coding: utf-8 -*-\n"""situations.py — GENERATED by a2_build/src/build_situations.py from\n'
            'a2_build/restage_bubbles.csv; do not edit by hand.\n\n'
            'The bubble-free "situation" staging (RESTAGE_PROPOSAL §2) for every card that used to\n'
            'carry a speech bubble (bubbles.py UTTER/EXCH, bubbles_a2.py, the question words, the\n'
            '3 IMG + 5 sentence bubble rows, 374 galvoti). Supersedes bubbles.py / bubbles_a2.py,\n'
            'which stay for history only.\n\n'
            'SITUATIONS: english gloss -> {ids, lithuanian, format ("situation" | "situation_2" |\n'
            '  "sequence" | "" = no image), scene, cue, confusables, merge_with, render, note, source_file}\n'
            'BY_ID: card id ("A2-0882", "374", "S-0014") -> english gloss\n"""\n')
    f.write("SITUATIONS = " + pprint.pformat(sit, width=110, sort_dicts=False) + "\n\n")
    f.write("BY_ID = " + pprint.pformat(by_id, width=110) + "\n\n\n")
    f.write('def renders(en):\n    """True if this gloss gets its own situation render."""\n'
            '    e = SITUATIONS.get(en)\n    return bool(e and e["render"].startswith("yes") and e["format"])\n')
print(len(sit), "situations,", sum(1 for e in sit.values() if e["render"].startswith("yes")), "render;", len(by_id), "ids ->", OUT)
